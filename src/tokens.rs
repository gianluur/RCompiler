use {crate::interner::SourceLiteral, core::fmt};

#[derive(Debug, PartialEq, Clone, Copy)]
pub struct Token {
    pub kind: TokenKind,
    pub span: TokenSpan,
}

#[derive(Debug, PartialEq, Clone, Copy)]
pub enum TokenKind {
    Eof,
    Semicolon,
    Comma,
    Dot,
    IntegerLiteral,
    FloatLiteral,
    CharLiteral,
    StringLiteral,
    BooleanLiteral,
    Plus,
    Minus,
    Multiplication,
    Division,
    Modulus,
    LeftParen,
    RightParen,
    LeftBracket,
    RightBracket,
    LeftBrace,
    RightBrace,
    BitwiseAnd,
    BitwiseOr,
    BitwiseXor,
    BitwiseLShift,
    BitwiseRShift,
    And,
    Or,
    Not,
    Equal,
    NotEqual,
    GreaterThan,
    LessThan,
    GreaterThanOrEqual,
    LessThanOrEqual,
    Assignment,
    AdditionAssignment,
    SubtractAssignment,
    MultiplyAssignment,
    DivideAssignment,
    ModulusAssignment,
    BitwiseAndAssignment,
    BitwiseOrAssignment,
    BitwiseXorAssignment,
    BitwiseLShiftAssignment,
    BitwiseRShiftAssignment,
    Identifier,
    Const,
    Int8,
    Int16,
    Int32,
    Int64,
    UInt8,
    UInt16,
    UInt32,
    UInt64,
    Float32,
    Float64,
    Boolean,
    Character,
    String,
    Null,
    If,
    ElseIf,
    Else,
    While,
    Break,
    Continue,
    Function,
    Return,
}

impl fmt::Display for TokenKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Eof => write!(f, "EOF"),
            Self::Comma => write!(f, ","),
            Self::Dot => write!(f, "."),
            Self::Semicolon => write!(f, ";"),
            Self::IntegerLiteral => write!(f, "IntegerLiteral"),
            Self::FloatLiteral => write!(f, "FloatLiteral"),
            Self::CharLiteral => write!(f, "CharLiteral"),
            Self::StringLiteral => write!(f, "StringLiteral"),
            Self::BooleanLiteral => write!(f, "BooleanLiteral"),
            Self::Plus => write!(f, "+"),
            Self::Minus => write!(f, "-"),
            Self::Multiplication => write!(f, "*"),
            Self::Division => write!(f, "/"),
            Self::Modulus => write!(f, "%"),
            Self::LeftParen => write!(f, "("),
            Self::RightParen => write!(f, ")"),
            Self::LeftBracket => write!(f, "["),
            Self::RightBracket => write!(f, "]"),
            Self::LeftBrace => write!(f, "{{"),
            Self::RightBrace => write!(f, "}}"),
            Self::BitwiseAnd => write!(f, "&"),
            Self::BitwiseOr => write!(f, "|"),
            Self::BitwiseXor => write!(f, "^"),
            Self::BitwiseLShift => write!(f, ">>"),
            Self::BitwiseRShift => write!(f, "<<"),
            Self::And => write!(f, "&&"),
            Self::Or => write!(f, "||"),
            Self::Not => write!(f, "!"),
            Self::Equal => write!(f, "=="),
            Self::NotEqual => write!(f, "!="),
            Self::GreaterThan => write!(f, ">"),
            Self::LessThan => write!(f, "<LessThan>"),
            Self::GreaterThanOrEqual => write!(f, ">="),
            Self::LessThanOrEqual => write!(f, "<="),
            Self::Assignment => write!(f, "="),
            Self::AdditionAssignment => write!(f, "+="),
            Self::SubtractAssignment => write!(f, "-="),
            Self::MultiplyAssignment => write!(f, "*="),
            Self::DivideAssignment => write!(f, "/="),
            Self::ModulusAssignment => write!(f, "%="),
            Self::BitwiseAndAssignment => write!(f, "&="),
            Self::BitwiseOrAssignment => write!(f, "|="),
            Self::BitwiseXorAssignment => write!(f, "^="),
            Self::BitwiseLShiftAssignment => write!(f, ">>="),
            Self::BitwiseRShiftAssignment => write!(f, "<<="),
            Self::Identifier => write!(f, "Identifier"),
            Self::Const => write!(f, "const"),
            Self::Int8 => write!(f, "i8"),
            Self::Int16 => write!(f, "i16"),
            Self::Int32 => write!(f, "i32"),
            Self::Int64 => write!(f, "i64"),
            Self::UInt8 => write!(f, "u8"),
            Self::UInt16 => write!(f, "u16"),
            Self::UInt32 => write!(f, "u32"),
            Self::UInt64 => write!(f, "u64"),
            Self::Float32 => write!(f, "f32"),
            Self::Float64 => write!(f, "f64"),
            Self::Boolean => write!(f, "bool"),
            Self::Character => write!(f, "char"),
            Self::String => write!(f, "str"),
            Self::Null => write!(f, "null"),
            Self::If => write!(f, "if"),
            Self::ElseIf => write!(f, "elif"),
            Self::Else => write!(f, "else"),
            Self::While => write!(f, "while"),
            Self::Break => write!(f, "break"),
            Self::Continue => write!(f, "continue"),
            Self::Function => write!(f, "fn"),
            Self::Return => write!(f, "return"),
        }
    }
}

#[derive(Debug, PartialEq, Clone, Copy)]
pub struct TokenSpan {
    pub start: usize,
    pub end: usize,
    pub literal: SourceLiteral,
    pub line: usize,
    pub column: usize,
}

impl TokenSpan {
    pub fn new(
        start: usize,
        end: usize,
        literal: SourceLiteral,
        line: usize,
        column: usize,
    ) -> Self {
        Self {
            start,
            end,
            literal,
            line,
            column,
        }
    }
}
